#!/usr/bin/env python3
"""Measure the Hafs letters shown in the mistake tray and write src/lib/letterFitData.ts.

Run from the repo root:
    pip install fonttools brotli uharfbuzz
    python3 scripts/build-letter-fit.py

Re-run it whenever public/fonts/hafs.18.woff2 changes. It reads only that font.

What it records, per letter, in font units: the advance width and the ink box
(xMin, yMin, xMax, yMax) of the glyph the browser draws when the letter stands
alone in a tile. The required uharfbuzz check also shapes each letter on its
own and stops if shaping picks a different glyph or adds an offset, because the
measured box would then be the wrong one.
"""
from __future__ import annotations

import json
import sys
from io import BytesIO
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "public" / "fonts" / "hafs.18.woff2"
OUT = ROOT / "src" / "lib" / "letterFitData.ts"

# Every glyph `primaryGlyph` can hold: base letters, ء for all hamza carriers,
# and ٱ. Lam-alef is shown as ل (see judgingUnits.ts), so it needs no entry.
TILE_LETTERS = "ءابتثجحخدذرزسشصضطظعغفقكلمنهوىيةٱ"
# Letters used to set the one shared baseline (ٱ left out: its wasla mark is
# not part of the letter's body).
BASELINE_SET = TILE_LETTERS.replace("ٱ", "")
# A letter counts as "tailed" when its ink drops this far below the baseline.
TAIL_DEPTH = -500


def main() -> int:
    font = TTFont(str(FONT))
    upm = font["head"].unitsPerEm
    hhea, os2 = font["hhea"], font["OS/2"]
    ascent, descent = hhea.ascent, -hhea.descent
    # Browsers read hhea (macOS, Linux) or OS/2 win metrics (Windows). The fit
    # maths assumes they agree; stop if a new font breaks that.
    if (os2.usWinAscent, os2.usWinDescent) != (ascent, descent):
        print(f"hhea {ascent}/{descent} differs from OS/2 win {os2.usWinAscent}/{os2.usWinDescent}", file=sys.stderr)
        return 1

    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    ink: dict[str, list[int]] = {}
    for ch in TILE_LETTERS:
        name = cmap.get(ord(ch))
        if name is None:
            print(f"font has no glyph for {ch} (U+{ord(ch):04X})", file=sys.stderr)
            return 1
        pen = BoundsPen(glyphs)
        glyphs[name].draw(pen)
        x_min, y_min, x_max, y_max = (round(v) for v in pen.bounds)
        ink[ch] = [glyphs[name].width, x_min, y_min, x_max, y_max]

    check_shaping(font, cmap)

    tailed = [ch for ch in BASELINE_SET if ink[ch][2] < TAIL_DEPTH]
    top = max(ink[ch][4] for ch in BASELINE_SET)
    bottom = min(ink[ch][2] for ch in BASELINE_SET)
    shared_mid = round((top + bottom) / 2)

    rows = ",\n".join(f'  "{ch}": [{", ".join(str(v) for v in ink[ch])}]' for ch in TILE_LETTERS)
    OUT.write_text(
        "// Generated by scripts/build-letter-fit.py from public/fonts/hafs.18.woff2.\n"
        "// Do not edit by hand; re-run the script if the font changes.\n"
        "//\n"
        "// Font units. Each entry: [advance, xMin, yMin, xMax, yMax] of the glyph\n"
        "// drawn when the letter stands alone (checked against HarfBuzz shaping).\n\n"
        f"export const HAFS_UNITS_PER_EM = {upm};\n"
        f"export const HAFS_ASCENT = {ascent};\n"
        f"export const HAFS_DESCENT = {descent};\n\n"
        "export type LetterInk = readonly [advance: number, xMin: number, yMin: number, xMax: number, yMax: number];\n\n"
        "export const LETTER_INK: Readonly<Record<string, LetterInk>> = {\n"
        f"{rows}\n"
        "};\n\n"
        f"/** Letters whose ink drops below {TAIL_DEPTH} units (the tails that make them sit low). */\n"
        f"export const TAILED_LETTERS: readonly string[] = {json.dumps(tailed, ensure_ascii=False)};\n\n"
        "/** Middle of the tallest top and deepest tail across the tile letters, in font units\n"
        " *  above the baseline. The shared-baseline fit puts this point on the tile centre. */\n"
        f"export const SHARED_BASELINE_MID = {shared_mid};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(ink)} letters, {len(tailed)} tailed, shared mid {shared_mid}")
    return 0


def check_shaping(font: TTFont, cmap: dict[int, str]) -> None:
    try:
        import uharfbuzz as hb
    except ImportError as exc:
        raise SystemExit("Install uharfbuzz: the shaping check is required.") from exc
    order = font.getGlyphOrder()
    with BytesIO() as tmp:
        font.flavor = None  # write plain TrueType; HarfBuzz cannot read WOFF2
        font.save(tmp)
        hb_font = hb.Font(hb.Face(tmp.getvalue()))
        for ch in TILE_LETTERS:
            buf = hb.Buffer()
            buf.add_str(ch)
            buf.guess_segment_properties()
            hb.shape(hb_font, buf)
            names = [order[info.codepoint] for info in buf.glyph_infos]
            offsets = [(p.x_offset, p.y_offset) for p in buf.glyph_positions]
            if names != [cmap[ord(ch)]] or any(offsets[0]):
                raise SystemExit(f"{ch}: shaping draws {names} {offsets}, not the measured glyph")


if __name__ == "__main__":
    raise SystemExit(main())
